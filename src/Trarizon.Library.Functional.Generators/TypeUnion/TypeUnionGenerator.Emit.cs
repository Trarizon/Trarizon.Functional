                writer.WriteLine("switch (this.__um_flag)");
                using (writer.EnterBracketIndentScope('{'))
                {
                    writer.WriteLine($"case {LiteralFlag(0, data)}:");
                    writer.WriteLine($"    return null;");
                    foreach (var variant in data.Variants)
                    {
                        writer.WriteLine($"case {LiteralFlag(variant.Id, data)}:");
                        if (variant.TypeData.TypeKind is VariantTypeKind.Reference)
                            writer.WriteLine($"    return {ExprVariantToT(variant, "object")};");
                        else
                            writer.WriteLine($"    return {ExprVariantToT(variant, variant.TypeData.FullyQName)};");
                    }
                }
                writer.WriteLine("return null;");
            }
        }
    }

    // emit: Shared interfaces

    private void EmitSharedInterfaceImplementations(IndentedTextWriter writer, ITypeUnionEmitter emitter, TypeUnionData data, Env env)
    {
        foreach (var intf in data.SharedInterfaces ?? [])
        {
            foreach (var member in intf.Members)
            {
                var @static = member.IsStatic ? "static " : "";
                var returnTypeRef = member.ReturnTypeRefKind switch
                {
                    RefKind.Ref => "ref ",
                    RefKind.RefReadOnly => "ref readonly ",
                    _ => ""
                };
                var returnRef = member.ReturnTypeRefKind switch
                {
                    RefKind.Ref or RefKind.RefReadOnly => "ref ",
                    _ => ""
                };
                var parameters = member.Parameters.Select(p => $"{p.TypeFQName} {p.Name}").JoinToString(", ");
                var arguments = member.Parameters.Select(p => p.Name).JoinToString(", ");
                var typeParameters = member.TypeParameters.Select(x => x.Name).JoinToString(", ");

                writer.WriteLine(Utils.GeneratedCodeAttributeList);
                switch (member.Kind)
                {
                    case InterfaceMemberKind.Property:
                        writer.WriteLine($"{@static}{returnTypeRef}{member.ReturnTypeFQName} {intf.TypeFQName}.{member.Name}");
                        using (writer.EnterBracketIndentScope('{'))
                        {
                            if (member.HasGetOrAddAccessor)
                            {
                                writer.WriteLine("get");
                                using (writer.EnterBracketIndentScope('{'))
                                {
                                    emitter.EmitSharedInterfaceDispatch(writer, env, data, false, value => $"{returnRef}(({intf.TypeFQName})({value})).{member.Name}");
                                }
                            }
                            if (member.HasSetOrRemoveAccessor)
                            {
                                writer.WriteLine(member.IsInitAccessor ? "init" : "set");
                                using (writer.EnterBracketIndentScope('{'))
                                {
                                    emitter.EmitSharedInterfaceDispatch(writer, env, data, true, value => $"(({intf.TypeFQName})({value})).{member.Name} = value;");
                                }
                            }
                        }
                        break;
                    case InterfaceMemberKind.Indexer:
                        writer.WriteLine($"{@static}{returnTypeRef}{member.ReturnTypeFQName} {intf.TypeFQName}.{member.Name}[{parameters}]");
                        using (writer.EnterBracketIndentScope('{'))
                        {
                            if (member.HasGetOrAddAccessor)
                            {
                                writer.WriteLine("get");
                                using (writer.EnterBracketIndentScope('{'))
                                {
                                    emitter.EmitSharedInterfaceDispatch(writer, env, data, false, value => $"{returnRef}(({intf.TypeFQName})({value})).{member.Name}[{arguments}];");
                                }
                            }
                            if (member.HasSetOrRemoveAccessor)
                            {
                                writer.WriteLine(member.IsInitAccessor ? "init" : "set");
                                using (writer.EnterBracketIndentScope('{'))
                                {
                                    emitter.EmitSharedInterfaceDispatch(writer, env, data, true, value => $"(({intf.TypeFQName})({value})).{member.Name}[{arguments}] = value;");
                                }
                            }
                        }
                        break;
                    case InterfaceMemberKind.Event:
                        writer.WriteLine($"{@static}{returnTypeRef}{member.ReturnTypeFQName} {intf.TypeFQName}.{member.Name}");
                        using (writer.EnterBracketIndentScope('{'))
                        {
                            if (member.HasGetOrAddAccessor)
                            {
                                writer.WriteLine("add");
                                using (writer.EnterBracketIndentScope('{'))
                                {
                                    emitter.EmitSharedInterfaceDispatch(writer, env, data, true, value => $"(({intf.TypeFQName})({value})).{member.Name} += value;");
                                }
                            }
                            if (member.HasSetOrRemoveAccessor)
                            {
                                writer.WriteLine("remove");
                                using (writer.EnterBracketIndentScope('{'))
                                {
                                    emitter.EmitSharedInterfaceDispatch(writer, env, data, true, value => $"(({intf.TypeFQName})({value})).{member.Name} -= value;");
                                }
                            }
                        }
                        break;
                    case InterfaceMemberKind.Method:
                        var tp = string.IsNullOrEmpty(typeParameters) ? "" : $"<{typeParameters}>";
                        writer.WriteLine($"{@static}{returnTypeRef}{member.ReturnTypeFQName} {intf.TypeFQName}.{member.Name}{tp}({parameters})");
                        using (writer.EnterBracketIndentScope('{'))
                        {
                            emitter.EmitSharedInterfaceDispatch(writer, env, data, member.ReturnsVoid, value => $"{returnRef}(({intf.TypeFQName})({value})).{member.Name}{tp}({arguments});");
                        }
                        break;
                }

                writer.WriteLine();
            }
        }
    }

    // expr

    private string ExprVariantFieldAccess(VariantData variant, string @this = "this")
    {
        return variant.TypeData.TypeKind switch
        {
            VariantTypeKind.Pointer => $"{@this}.__um_unmanaged._ptr",
            VariantTypeKind.FunctionPointer => $"{@this}.__um_unmanaged._ptr",
            VariantTypeKind.Unmanaged => $"{@this}.__um_unmanaged._{variant.FieldId}",
            VariantTypeKind.Reference => $"{@this}.__um_obj",
            VariantTypeKind.Managed => $"{@this}.__um_managed{variant.FieldId}",
            _ => throw new NotSupportedException($"TypeKind {variant.TypeData.TypeKind} is not supported."),
        };
    }

    // The return expression can be ref-ed
    private string ExprVariantRefToT(VariantData variant, string targetType = "T", string @this = "this")
    {
        var fieldFullyQualifiedTypeName = variant.TypeData.TypeKind switch
        {
            VariantTypeKind.Reference => "object",
            { IsPointer: true } => "global::System.IntPtr",
            _ => variant.TypeData.FullyQName,
        };
        if (fieldFullyQualifiedTypeName == targetType)
            return ExprVariantFieldAccess(variant, @this);
        return $"global::System.Runtime.CompilerServices.Unsafe.As<{fieldFullyQualifiedTypeName}, {targetType}>(ref global::System.Runtime.CompilerServices.Unsafe.AsRef<{fieldFullyQualifiedTypeName}>(in {ExprVariantFieldAccess(variant, @this)}))";
    }

    // The return expression maybe cannot be ref-ed
    private string ExprVariantToT(VariantData variant, string? targetType = null, string @this = "this")
    {
        if (!variant.TypeData.TypeKind.IsPointer)
            return ExprVariantRefToT(variant, targetType ?? "T", @this);

        if (targetType is null)
        {
            var chars = (stackalloc char[variant.TypeData.PointerLevel + 1]);
            chars.Fill('*');
            chars[0] = 'T';
            targetType = chars.ToString();
        }

        return $"({targetType}){ExprVariantFieldAccess(variant, @this)}";
    }

    // doc

    private static string DocCommentIsExactly(string type, bool code = true)
    {
        return $$"""
            /// <summary>
            /// Check if the union value is type {{(code ? $"<c>{type}</c>" : type)}}
            /// </summary>
            """;
    }

    static string DocCommentAsExactly(string type, bool code = true)
    {
        return $$"""
            /// <summary>
            /// Check if the union value is exactly type {{(code ? $"<c>{type}</c>" : type)}}, and return the value if it is.
            /// </summary>
            """;
    }

    private static string LiteralFlag(uint value, TypeUnionData data)
    {
        var suffix = data.Variants.Length switch
        {
            <= 255 => "",
            <= 65535 => "",
            _ => "u",
        };
        return $"{value}{suffix}";
    }

